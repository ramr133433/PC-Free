#!/usr/bin/env bash
# One-file PC-Free launcher: Windows 10/11, separate persistent disks.
set -Eeuo pipefail

IMAGE="dockurr/windows"
ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
cd "$ROOT"
CFG=".pcfree-config"
DATA=".pcfree-data"
W10="pcfree-windows10"
W11="pcfree-windows11"

info(){ echo "[PC-Free] $*"; }
die(){ echo "[ERROR] $*" >&2; exit 1; }
ok(){ echo "[OK] $*"; }

ignore_line() {
  touch .gitignore
  grep -qxF "$1" .gitignore 2>/dev/null || echo "$1" >> .gitignore
}

prerequisites() {
  command -v docker >/dev/null || die "Docker command nahi mila."
  command -v curl >/dev/null || die "curl available nahi."
  docker info >/dev/null 2>&1 || die "Docker daemon available nahi."
  [ -c /dev/kvm ] || die "/dev/kvm missing. Is Codespace par KVM unavailable hai; Windows VM start nahi ho sakti."
  [ -c /dev/net/tun ] || die "/dev/net/tun missing."
  free_kb="$(df -Pk "$ROOT" | awk 'NR==2{print $4}')"
  [ "${free_kb:-0}" -ge 30000000 ] || die "Workspace mein 30 GB free disk nahi. Windows setup ke liye space kam hai."
  ok "Docker, KVM, TUN aur disk check pass."
  free -h || true
  df -h "$ROOT" || true
}

make_private_dirs() {
  ignore_line "$CFG"
  ignore_line "$DATA/"
  mkdir -p "$DATA/win10" "$DATA/win11"
  chmod 700 "$DATA" "$DATA/win10" "$DATA/win11" 2>/dev/null || true
}

setup_config() {
  if [ ! -f "$CFG" ]; then
    echo "First-time setup:"
    read -r -p "GitHub username: " GITHUB_USER
    [[ "$GITHUB_USER" =~ ^[a-zA-Z0-9-]{1,39}$ ]] || die "GitHub username invalid."
    read -r -p "Windows username [Docker]: " WINDOWS_USERNAME
    WINDOWS_USERNAME="${WINDOWS_USERNAME:-Docker}"
    [[ "$WINDOWS_USERNAME" =~ ^[a-zA-Z0-9._-]{1,20}$ ]] || die "Windows username invalid."
    read -r -s -p "Windows password (minimum 8 characters): " pw
    echo
    [ "${#pw}" -ge 8 ] || die "Password kam az kam 8 characters ka ho."
    pw64="$(printf '%s' "$pw" | base64 | tr -d '\n')"
    unset pw
    {
      printf 'GITHUB_USER=%s\n' "$GITHUB_USER"
      printf 'WINDOWS_USERNAME=%s\n' "$WINDOWS_USERNAME"
      printf 'WINDOWS_PASSWORD_B64=%s\n' "$pw64"
    } > "$CFG"
    chmod 600 "$CFG"
    unset pw64
    ok "Private config saved. Base64 password encryption nahi hota; file local/private rakho."
  fi
  # Config is generated by this script; usernames are validated on creation.
  # shellcheck disable=SC1090
  source "$CFG"
  WINDOWS_PASSWORD="$(printf '%s' "$WINDOWS_PASSWORD_B64" | base64 -d)"
  [ -n "${WINDOWS_PASSWORD:-}" ] || die "Saved Windows password missing/invalid."
}

follow_check() {
  info "GitHub follow status check: $GITHUB_USER → jephersonRD"
  code="$(curl -L -sS -o /dev/null -w '%{http_code}' \
    -H 'Accept: application/vnd.github+json' \
    "https://api.github.com/users/${GITHUB_USER}/following/jephersonRD" || true)"
  case "$code" in
    204) ok "Follow verified." ;;
    404) die "$GITHUB_USER jephersonRD ko follow nahi karta. Follow kar ke dobara run karo." ;;
    403) die "GitHub API rate limit/access restriction. Kuch der baad retry karo." ;;
    *) die "GitHub follow check failed (HTTP ${code:-unknown}); network/API check karo." ;;
  esac
}

exists(){ docker inspect "$1" >/dev/null 2>&1; }
running(){ [ "$(docker inspect -f '{{.State.Running}}' "$1" 2>/dev/null || echo false)" = true ]; }

stop_one() {
  if running "$1"; then
    info "$1 stopping..."
    docker stop --time 120 "$1" >/dev/null
    ok "$1 stopped; disk preserved."
  fi
}

start_one() {
  local ver="$1" name="$2" folder="$3" other="$4"
  prerequisites
  follow_check
  stop_one "$other"

  if exists "$name"; then
    if running "$name"; then
      ok "Windows $ver already running."
    else
      info "Existing Windows $ver resume..."
      docker start "$name" >/dev/null
    fi
  else
    info "First Windows $ver install: image download and Windows setup may take time."
    docker run -d \
      --name "$name" \
      --label pcfree.managed=true \
      --device=/dev/kvm \
      --device=/dev/net/tun \
      --cap-add NET_ADMIN \
      --stop-timeout 120 \
      -p 8006:8006 \
      -e "VERSION=$ver" \
      -e "USERNAME=$WINDOWS_USERNAME" \
      -e "PASSWORD=$WINDOWS_PASSWORD" \
      -e "RAM_SIZE=4G" \
      -e "CPU_CORES=2" \
      -e "DISK_SIZE=40G" \
      -v "$ROOT/$DATA/$folder:/storage" \
      "$IMAGE" >/dev/null
  fi
  ok "Windows $ver start/resume request sent."
  info "Codespace ke Ports tab mein port 8006 → Open in Browser. Visibility Private rakho."
}

status() {
  docker ps -a --filter "name=pcfree-windows" \
    --format 'table {{.Names}}\t{{.Status}}\t{{.Ports}}' || true
  du -sh "$DATA/win10" "$DATA/win11" 2>/dev/null || true
}

prerequisites
make_private_dirs
setup_config

while true; do
  echo
  echo "========== PC-FREE =========="
  echo "1) Windows 10 start / resume"
  echo "2) Windows 11 start / resume"
  echo "3) Dono Windows stop"
  echo "4) Status / storage"
  echo "5) Logs (10)"
  echo "6) Logs (11)"
  echo "7) Exit"
  read -r -p "Select [1-7]: " choice
  case "$choice" in
    1) start_one 10 "$W10" win10 "$W11" ;;
    2) start_one 11 "$W11" win11 "$W10" ;;
    3) stop_one "$W10"; stop_one "$W11"; ok "Stop command complete." ;;
    4) status ;;
    5) docker logs --tail 100 -f "$W10" ;;
    6) docker logs --tail 100 -f "$W11" ;;
    7) unset WINDOWS_PASSWORD 2>/dev/null || true; info "Exit. Running VM automatically stop nahi hogi."; exit 0 ;;
    *) echo "Invalid choice." ;;
  esac
done
